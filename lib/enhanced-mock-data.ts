export function getChartData(biomarkerId: number) {
  const biomarker = biomarkersWithCharts.find((b) => b.id === biomarkerId);
  if (!biomarker) return null;

  return {
    labels: biomarker.readings.map((r) => r.date.split(' ')[0]),
    datasets: [
      {
        data: biomarker.readings.map((r) => r.value),
        strokeWidth: 2,
        color: () => biomarker.color,
      },
    ],
    referenceMin: biomarker.referenceMin,
    referenceMax: biomarker.referenceMax,
  };
}
